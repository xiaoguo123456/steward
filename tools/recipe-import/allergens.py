def _self_check() -> int:
    failed = 0
    for ings, must, must_not in CASES:
        got = detect(ings)
        for label in must:
            if label not in got:
                print(f"  漏标：{ings} 应含「{label}」，实际 {got}")
                failed += 1
        for label in must_not:
            if label in got:
                print(f"  误标：{ings} 不该含「{label}」，实际 {got}")
                failed += 1
    print(f"自检 {len(CASES)} 条，失败 {failed} 项")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(_self_check())
