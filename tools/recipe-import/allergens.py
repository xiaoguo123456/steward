def detect(ingredient_names: list[str]) -> list[str]:
    """返回这道菜命中的过敏原标签，已去重并按固定顺序排列。"""
    hits: list[str] = []
    for label, keywords, excludes in RULES:
        for raw in ingredient_names:
            name = (raw or "").strip()
            if not name:
                continue
            if any(bad in name for bad in excludes):
                continue
            if any(kw in name for kw in keywords):
                hits.append(label)
                break
    return hits


