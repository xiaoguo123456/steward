export type SportModeIconName = 'running' | 'walking' | 'cycling' | 'strength';

const sportModeIconSpecs = {
  running: { icon: RunningShoesIcon, opticalScale: 1.02 },
  walking: { icon: WalkingIcon, opticalScale: 1 },
  cycling: { icon: BicycleIcon, opticalScale: 1.04 },
  strength: { icon: Dumbbell01Icon, opticalScale: 1.02 },
} satisfies Record<
  SportModeIconName,
  { icon: HugeIconData; opticalScale: number }
>;

type SportModeIconProps = {
  mode: SportModeIconName;
  size?: number;
  color?: string;
};

export function SportModeIcon({
  mode,
  size = 28,
  color = colors.primaryStrong,
}: SportModeIconProps) {
  const spec = sportModeIconSpecs[mode];
  const renderedSize = Math.round(size * spec.opticalScale);

  return (
    <HugeiconsIcon
      accessible={false}
      color={color}
      icon={spec.icon}
      size={renderedSize}
      strokeWidth={1.8}
    />
  );
}
